import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { PRODUCT_VERSION } from "./product-version.mjs";

const repositoryRoot = resolve(new URL("..", import.meta.url).pathname);
const packagePaths = ["apps/runner/package.json", "apps/worker/package.json", "packages/protocol/package.json"];
const readJson = async (relativePath) => JSON.parse(await readFile(resolve(repositoryRoot, relativePath), "utf8"));
const errors = [];
for (const relativePath of packagePaths) {
  const manifest = await readJson(relativePath);
  if (manifest.version !== PRODUCT_VERSION) errors.push(`${relativePath}.version=${manifest.version ?? "<missing>"}`);
  const protocolVersion = relativePath === "apps/worker/package.json"
    ? manifest.dependencies?.["@aloneio/runmesh-protocol"]
    : relativePath === "apps/runner/package.json"
      ? manifest.devDependencies?.["@aloneio/runmesh-protocol"]
      : undefined;
  if (relativePath !== "packages/protocol/package.json" && protocolVersion !== PRODUCT_VERSION) {
    errors.push(`${relativePath}: protocol dependency=${protocolVersion ?? "<missing>"}`);
  }
}
const generatedWorkerVersion = await readFile(resolve(repositoryRoot, "apps/worker/src/generated-version.ts"), "utf8");
const expectedGeneratedWorkerVersion = `// Generated by scripts/generate-version-modules.mjs from root package.json.\nexport const PRODUCT_VERSION = ${JSON.stringify(PRODUCT_VERSION)};\n`;
if (generatedWorkerVersion !== expectedGeneratedWorkerVersion) errors.push("apps/worker/src/generated-version.ts is not synchronized");
const lock = await readJson("package-lock.json");
if (lock.version !== PRODUCT_VERSION || lock.packages?.[""]?.version !== PRODUCT_VERSION) errors.push("package-lock root version is not synchronized");
for (const relativePath of ["apps/runner", "apps/worker", "packages/protocol"]) {
  const entry = lock.packages?.[relativePath];
  if (entry?.version !== PRODUCT_VERSION) errors.push(`package-lock ${relativePath} version is not synchronized`);
  const protocolVersion = entry?.dependencies?.["@aloneio/runmesh-protocol"] ?? entry?.devDependencies?.["@aloneio/runmesh-protocol"];
  if (relativePath !== "packages/protocol" && protocolVersion !== PRODUCT_VERSION) errors.push(`package-lock ${relativePath}: protocol dependency=${protocolVersion ?? "<missing>"}`);
}
if (errors.length > 0) throw new Error(`version synchronization failed:\n${errors.join("\n")}`);
console.log(`version synchronization is valid: ${PRODUCT_VERSION}`);
