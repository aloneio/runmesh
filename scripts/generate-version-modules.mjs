import { writeBuildProvenance } from "./build-provenance.mjs";
import { reviewedReleaseSource } from "./runtime-config-tools.mjs";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = JSON.parse(await readFile(resolve(repositoryRoot, "package.json"), "utf8")).version;
if (typeof version !== "string" || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(version)) {
  throw new Error("invalid root product version");
}
const source = `// Generated by scripts/generate-version-modules.mjs from root package.json.\nexport const PRODUCT_VERSION = ${JSON.stringify(version)};\n`;
const target = resolve(repositoryRoot, "apps/worker/src/generated-version.ts");
const existing = await readFile(target, "utf8").catch(() => undefined);
if (existing !== source) await writeFile(target, source, "utf8");

const releaseState = JSON.parse(await readFile(resolve(repositoryRoot, "release/release-state.json"), "utf8"));
const releaseSource = reviewedReleaseSource(version, releaseState);
const releaseTarget = resolve(repositoryRoot, "apps/worker/src/generated-release.ts");
if (await readFile(releaseTarget, "utf8").catch(() => undefined) !== releaseSource) await writeFile(releaseTarget, releaseSource, "utf8");

await writeBuildProvenance(repositoryRoot);
