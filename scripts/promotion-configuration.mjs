import { githubMainPromotion, gitlabMainPromotion } from "./main-promotion-policy.mjs";

const indent = (text, spaces) => text.split("\n").map(line => " ".repeat(spaces) + line).join("\n");
const image = "node:22.23.2-bookworm@sha256:8a34c4ab3ea2c5cd194f07e317b2a8f09461d3c8b05c4e34c8ccd56d56024c4d";

export function githubPolicyWorkflow() {
  const program = `const fs = require("node:fs");
${githubMainPromotion.toString()}
try {
  const path = process.env.GITHUB_EVENT_PATH;
  const info = fs.statSync(path);
  if (!info.isFile() || info.size > 2097152) throw new Error("invalid event input");
  console.log(JSON.stringify(githubMainPromotion(JSON.parse(fs.readFileSync(path, "utf8")), process.env)));
} catch {
  console.error("main_source_policy_denied: use a same-repository dev -> main pull request");
  process.exitCode = 1;
}`;
  return `# Generated by scripts/check-main-policy.mjs --write; review source and output together.
name: Main promotion policy

on:
  pull_request:
    branches: [main]
    types: [opened, reopened, synchronize, edited, ready_for_review]

# Metadata only: no checkout, npm install, secrets, write token or deployment.
permissions: {}

concurrency:
  group: main-source-policy-\${{ github.event.pull_request.number }}
  cancel-in-progress: true

jobs:
  main-source-policy:
    runs-on: ubuntu-latest
    timeout-minutes: 2
    steps:
      - name: Require same-repository dev source
        shell: bash
        run: |
          node <<'RUNMESH_POLICY'
${indent(program, 10)}
          RUNMESH_POLICY
`;
}

export function gitlabPolicyJob() {
  const program = `${gitlabMainPromotion.toString()}
try { console.log(JSON.stringify(gitlabMainPromotion(process.env))); }
catch {
  console.error("main_source_policy_denied: use a same-project dev -> main merge request");
  process.exitCode = 1;
}`;
  return `main-source-policy:
  stage: .pre
  image: ${image}
  inherit:
    default: false
    variables: false
  variables:
    GIT_STRATEGY: none
  cache: []
  dependencies: []
  needs: []
  before_script: []
  after_script: []
  services: []
  tags: []
  allow_failure: false
  interruptible: false
  timeout: 2m
  rules:
    - if: '$CI_PIPELINE_SOURCE == "merge_request_event"'
      when: on_success
    - when: never
  script:
    - |
      node <<'RUNMESH_POLICY'
${indent(program, 6)}
      RUNMESH_POLICY
`;
}

export function gitlabPolicyEntrypoint() {
  // Project setting selects this file from reviewed dev, not from the MR
  // source. The source revision still owns its ordinary test configuration.
  // Root-level gate values override corresponding included values.
  return `# Generated by scripts/check-main-policy.mjs --write.
# Install as .gitlab/main-policy.yml@<project-path>:dev in project CI settings.
include:
  - project: '$CI_PROJECT_PATH'
    ref: '$CI_COMMIT_SHA'
    file: '/.gitlab-ci.yml'

# Do not let an old/source configuration omit the mandatory MR gate.
workflow:
  rules:
    - if: '$CI_PIPELINE_SOURCE == "merge_request_event"'
    - if: '$CI_PIPELINE_SOURCE == "push" && $CI_COMMIT_BRANCH == "main"'
    - if: '$CI_PIPELINE_SOURCE == "web"'
    - if: '$CI_PIPELINE_SOURCE == "schedule"'
    - when: never

${gitlabPolicyJob()}`;
}

